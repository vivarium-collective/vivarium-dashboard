"""Generate the drift-prone README lists for a viva workspace.

Two Markdown tables are derived deterministically from the workspace itself and
injected between HTML marker comments in the workspace's ``README.md``:

  ``<!-- BEGIN:composites -->``      … ``<!-- END:composites -->``
      The workspace-local composites — exactly what the read-only dashboard's
      Composites page lists — via :func:`composites_data` (covers both
      ``@composite_generator`` Python composites and ``*.composite.{yaml,json}``
      documents). Each row is a composite name + its one-line description.

  ``<!-- BEGIN:investigations -->`` … ``<!-- END:investigations -->``
      The research investigations under the workspace's (layout-aware)
      ``investigations/`` directory, read from each ``investigation.yaml``
      (title + status + research question, linked to its published report).

Any workspace with a ``workspace.yaml`` can adopt this: add whichever markers it
wants to its README, then run ``vivarium-workbench gen-readme`` (and
``vivarium-workbench gen-readme --check`` in CI). Only blocks whose markers are
actually present are generated, so a workspace can opt into one, both, or
neither.
"""
from __future__ import annotations

import re
from pathlib import Path

GEN_NOTE = (
    "<!-- generated by `vivarium-workbench gen-readme` — edit the source, not this table -->"
)

_TAGS = ("dashboard", "composites", "investigations")


# --------------------------------------------------------------------------- #
# Text helpers
# --------------------------------------------------------------------------- #

def _md_cell(text: object) -> str:
    """Flatten a value into a single Markdown table cell."""
    return " ".join(str(text).split()).replace("|", "\\|")


def _first_sentence(text: object, limit: int = 200) -> str:
    """Collapse whitespace, keep the first sentence, cap length.

    The sentence-boundary test requires a lowercase/digit before the period and
    a capital after the space, so abbreviations like ``E. coli``, ``e.g.``,
    ``i.e.`` are not treated as boundaries.
    """
    flat = " ".join(str(text).split())
    m = re.search(r"(?<=[a-z0-9][.?!])\s+(?=[A-Z])", flat)
    if m and m.start() <= limit:
        flat = flat[: m.start() + 1].rstrip()
    if len(flat) > limit:
        flat = flat[: limit - 1].rstrip() + "…"
    return flat


# --------------------------------------------------------------------------- #
# Data sources
# --------------------------------------------------------------------------- #

def pages_base(ws_root: Path) -> str | None:
    """GitHub Pages base URL for the workspace repo, or None if not on GitHub.

    ``https://<owner>.github.io/<repo>`` — the project-pages root where the
    workspace publishes its dashboard + investigation reports.
    """
    try:
        from vivarium_workbench.lib.report import _detect_github_repo
    except Exception:
        return None
    slug = _detect_github_repo(Path(ws_root))  # "owner/repo" or None
    if not slug or "/" not in slug:
        return None
    owner, repo = slug.split("/", 1)
    return f"https://{owner}.github.io/{repo}"


def collect_composites(ws_root: Path) -> list[dict]:
    """Workspace-local composites (name + description), sorted by name."""
    from vivarium_workbench.lib.composite_lookup import composites_data

    data = composites_data(Path(ws_root))
    rows = [c for c in (data.get("composites") or []) if c.get("workspace_local")]
    rows.sort(key=lambda c: str(c.get("name") or ""))
    return rows


def collect_investigations(ws_root: Path) -> list[dict]:
    """Investigations under the layout-aware investigations dir."""
    import yaml

    from vivarium_workbench.lib.workspace_paths import WorkspacePaths

    inv_dir = WorkspacePaths.load(ws_root).investigations
    out: list[dict] = []
    if not inv_dir.is_dir():
        return out
    for yml in sorted(inv_dir.glob("*/investigation.yaml")):
        try:
            spec = yaml.safe_load(yml.read_text(encoding="utf-8")) or {}
        except Exception:
            spec = {}
        if not isinstance(spec, dict):
            spec = {}
        name = str(spec.get("name") or yml.parent.name)
        out.append({
            "name": name,
            "title": str(spec.get("title") or name),
            "question": str(spec.get("question") or ""),
            "status": str(spec.get("status") or "").strip(),
        })
    out.sort(key=lambda d: d["name"])
    return out


# --------------------------------------------------------------------------- #
# Table rendering
# --------------------------------------------------------------------------- #

def render_composites(rows: list[dict]) -> str:
    lines = [GEN_NOTE, "", "| Composite | What it is |", "|---|---|"]
    for c in rows:
        name = _md_cell(c.get("name") or "")
        desc = _md_cell(_first_sentence(c.get("description") or ""))
        lines.append(f"| `{name}` | {desc} |")
    return "\n".join(lines)


def render_dashboard(base: str | None) -> str:
    """Prominent live read-only-dashboard callout for the top of the README.

    Uses the GitHub Pages URL derived from the workspace's git remote; falls
    back to the local-serve instruction when the repo isn't on GitHub yet.
    """
    if base:
        url = f"{base}/dashboard/"
        return (
            f"{GEN_NOTE}\n\n"
            f"> ### 🔬 [Explore the interactive read-only dashboard →]({url})\n"
            f">\n"
            f"> Every composite, study, and result — browsable in your browser, no install required.\n"
            f"> Published from `main` by the `publish-dashboard` workflow (allow a few minutes after the first push)."
        )
    return (
        f"{GEN_NOTE}\n\n"
        f"> ### 🔬 Interactive read-only dashboard\n"
        f">\n"
        f"> Run `vivarium-workbench serve --workspace .` to explore every composite, study, and\n"
        f"> result in your browser. Once this workspace is pushed to GitHub, the `publish-dashboard`\n"
        f"> workflow publishes a live read-only version to GitHub Pages and this link fills in."
    )


def render_investigations(rows: list[dict], base: str | None) -> str:
    lines = [GEN_NOTE, "", "| Investigation | Research question |", "|---|---|"]
    for r in rows:
        label = _md_cell(r["title"])
        if r["status"]:
            label += f" _({_md_cell(r['status'])})_"
        cell = f"[{label}]({base}/investigations/{r['name']}.html)" if base else label
        lines.append(f"| {cell} | {_md_cell(_first_sentence(r['question']))} |")
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
# Marker injection
# --------------------------------------------------------------------------- #

def _has_markers(text: str, tag: str) -> bool:
    return f"<!-- BEGIN:{tag} -->" in text and f"<!-- END:{tag} -->" in text


def _replace_block(text: str, tag: str, body: str) -> str:
    begin, end = f"<!-- BEGIN:{tag} -->", f"<!-- END:{tag} -->"
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.DOTALL)
    return pattern.sub(lambda _m: f"{begin}\n{body}\n{end}", text)


def build_readme(text: str, ws_root: Path) -> str:
    """Return README ``text`` with every present marker block regenerated."""
    ws_root = Path(ws_root)
    if _has_markers(text, "dashboard"):
        text = _replace_block(text, "dashboard", render_dashboard(pages_base(ws_root)))
    if _has_markers(text, "composites"):
        text = _replace_block(text, "composites", render_composites(collect_composites(ws_root)))
    if _has_markers(text, "investigations"):
        base = pages_base(ws_root)
        text = _replace_block(
            text, "investigations", render_investigations(collect_investigations(ws_root), base)
        )
    return text


# --------------------------------------------------------------------------- #
# Entry point (used by the CLI)
# --------------------------------------------------------------------------- #

def generate(ws_root: Path | str, *, check: bool = False, readme: Path | None = None) -> int:
    """Regenerate (or ``--check``) a workspace README's generated sections.

    Returns a process exit code: 0 on success/up-to-date, 1 if ``check`` and the
    README is stale, 2 if there is nothing to do (no markers / no README).
    """
    ws_root = Path(ws_root).resolve()
    readme_path = Path(readme) if readme else ws_root / "README.md"
    if not readme_path.is_file():
        print(f"error: no README at {readme_path}", flush=True)
        return 2

    current = readme_path.read_text(encoding="utf-8")
    if not any(_has_markers(current, tag) for tag in _TAGS):
        print(
            f"error: {readme_path} has no <!-- BEGIN:dashboard/composites/investigations --> markers; "
            "add the markers where the generated dashboard link / tables should go.",
            flush=True,
        )
        return 2

    updated = build_readme(current, ws_root)

    if check:
        if current != updated:
            print(
                f"{readme_path} is stale — run: vivarium-workbench gen-readme --workspace {ws_root}",
                flush=True,
            )
            return 1
        print(f"{readme_path.name} generated sections are up to date.", flush=True)
        return 0

    if current != updated:
        readme_path.write_text(updated, encoding="utf-8")
        print(f"✓ regenerated {readme_path}", flush=True)
    else:
        print(f"{readme_path.name} already up to date.", flush=True)
    return 0
